-- Assertions run as SECURITY INVOKER under authenticated/anon, never as owner.
CREATE FUNCTION public.test_nexus_counts(label text, expected integer, invites integer DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER AS $$
DECLARE actual integer; t text;
BEGIN
  IF current_user NOT IN ('authenticated', 'anon') THEN
    RAISE EXCEPTION 'test_must_run_under_rls';
  END IF;
  FOREACH t IN ARRAY ARRAY['nexus_clinical_results','nexus_red_flags','nexus_self_assessment_invites'] LOOP
    EXECUTE format('SELECT count(*) FROM public.%I',t) INTO actual;
    IF actual <> (CASE WHEN t='nexus_self_assessment_invites' THEN coalesce(invites,expected) ELSE expected END) THEN
      RAISE EXCEPTION 'C01 assertion % table %: expected %, got %', label,t,
        CASE WHEN t='nexus_self_assessment_invites' THEN coalesce(invites,expected) ELSE expected END,actual;
    END IF;
  END LOOP;
END; $$;
